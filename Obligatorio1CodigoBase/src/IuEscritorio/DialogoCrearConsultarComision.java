    private void actualizarListaComisionesProductos() {
        Proveedor proveedorSeleccionado = (Proveedor) listaProveedores.getSelectedValue();
        ArrayList comisiones = proveedorSeleccionado.getComisiones();
        ArrayList productos = proveedorSeleccionado.getProductos();
        this.listaComisiones.setListData(comisiones.toArray());
        this.listaProductos.setListData(productos.toArray());

        if (comisiones.isEmpty()) {
            JOptionPane.showMessageDialog(null,
                    "No hay comisiones");
        }
        if (productos.isEmpty()) {
            JOptionPane.showMessageDialog(null,
                    "No hay productos");
        }
    }

    private void actualizarListaFacturas() {
        if (Comision.getMostrarInfoCompleta()) {
            Comision comisionSeleccionada = (Comision) this.listaComisiones.getSelectedValue();
            if (comisionSeleccionada != null) {
                Producto productoConsultar = comisionSeleccionada.getProducto();
                Factura.setProductoConsultar(productoConsultar);
                ArrayList<Factura> facturasComision = comisionSeleccionada.getFacturas();
                this.listaFacturasComision.setListData(facturasComision.toArray());
                if (facturasComision.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "No hay ventas");
                }
            } else {
                JOptionPane.showMessageDialog(null, "No hay ventas");
            }
        }
    }

    private void buttonCrearComisionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonCrearComisionActionPerformed
        try {
            Proveedor proveedorSeleccionado = (Proveedor) listaProveedores.getSelectedValue();
            Producto productoSeleccionado = (Producto) listaProductos.getSelectedValue();
            String nombreComision = this.textNombreComision.getText().trim();
            String txtPorcentaje = this.textPorcentajeComision.getText();
            if (!txtPorcentaje.isEmpty() && !txtPorcentaje.isBlank() && !nombreComision.isEmpty() && !nombreComision.isBlank()) {
                Float porcentajeComision = Float.parseFloat(txtPorcentaje.trim());
                if (!logica.buscarComisionesConMismoNombre(nombreComision)) {
                    Comision nuevaComision = new Comision(proveedorSeleccionado, productoSeleccionado, nombreComision, porcentajeComision);
                    if (nuevaComision.validar()) {
                        logica.agregarComision(nuevaComision);
                        actualizarListaComisionesProductos();
                        JOptionPane.showMessageDialog(null, "Agregada correctamente.");
                    } else {
                        throw new HeadlessException("Failed");
                    }
                } else {
                    throw new HeadlessException("Failed");
                }
            } else {
                throw new NumberFormatException("porcentaje vacio");
            }
        } catch (HeadlessException | NumberFormatException e) {
            JOptionPane.showMessageDialog(null,
                    "No se pudo crear la comision");
        } finally {

        }
    }//GEN-LAST:event_buttonCrearComisionActionPerformed

